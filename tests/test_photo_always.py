class SceneData(unittest.TestCase):
    def setUp(self):
        self.data = scenes.load()

    def test_every_topic_and_rule_has_at_least_four_photos(self):
        self.assertTrue(TOPICS | {"Sport"} <= set(self.data["topics"]))
        for name, items in self.data["topics"].items():
            self.assertGreaterEqual(len(items), 4, name)
        wanted = {"energy", "shipping", "banks", "chips", "cyber", "airlines", "cars", "retail", "jobs", "crypto", "realestate"}
        self.assertTrue(wanted <= {r["id"] for r in self.data["rules"]})
        for rule in self.data["rules"]:
            re.compile(rule["match"])
            self.assertGreaterEqual(len(rule["files"]), 4, rule["id"])

    def test_every_file_is_a_jpeg_with_an_alt_text_and_none_repeats_in_a_list(self):
        for items in [r["files"] for r in self.data["rules"]] + list(self.data["topics"].values()):
            files = [i["file"] for i in items]
            self.assertEqual(len(files), len(set(files)))
            for i in items:
                self.assertRegex(i["file"], r"(?i)\.jpe?g$")
                self.assertTrue(i["alt"].strip())

    def test_the_headline_picks_its_entry_then_the_topic(self):
        lists = scenes.entries("Maltese-flagged tanker capsizes off Ibiza", "World", self.data)
        self.assertEqual(lists[0], next(r["files"] for r in self.data["rules"] if r["id"] == "shipping"))
        self.assertEqual(lists[1], self.data["topics"]["World"])
        # a landmark (the Vasconcelos library) only goes on an article about its place
        self.assertEqual(scenes.entries("A quiet day", "Culture", self.data)[0],
                         [i for i in self.data["topics"]["Culture"] if scenes.fits(i, "A quiet day")])


class SportScenes(unittest.TestCase):
    def test_every_sport_has_a_vetted_scene_and_a_keyword_route(self):
        data = scenes.load()
        self.assertEqual({r["id"] for r in data["sport"]}, {"f1", "nfl", "nba", "tennis", "cricket", "golf", "boxing", "olympics", "football"})
        for text, want in (("Sinner ruled out of Australian Open", "tennis"), ("Russell laughs off Verstappen Las Vegas Grand Prix", "f1"),
                           ("Steelers owner backs McCarthy as quarterback leaves NFL team", "nfl"), ("Sunderland draw in the Europa League", "football")):
            first = scenes.entries(text, "Sport", data, sport=True)[0]
            self.assertEqual(first, next(r["files"] for r in data["sport"] if r["id"] == want), text)

    def test_the_news_rules_do_not_read_a_sport_headline(self):
        data = scenes.load()
        # "city" and "united" in a club name must not send a sport story to the news lists
        self.assertEqual(scenes.entries("Manchester City beat United", "Sport", data, sport=True)[0],
                         next(r["files"] for r in data["sport"] if r["id"] == "football"))


class Rotation(unittest.TestCase):
    items = [{"file": f"{c}.jpg", "alt": c} for c in "abcd"]

    def test_unused_files_come_first(self):
        first = scenes.order(self.items, {"a.jpg", "b.jpg"}, seed="x")
        self.assertEqual({i["file"] for i in first[:2]}, {"c.jpg", "d.jpg"})

    def test_when_all_are_used_the_oldest_use_comes_first(self):
        last = {"a.jpg": "2026-11-26T10:00", "b.jpg": "2026-11-20T10:00", "c.jpg": "2026-11-25T10:00", "d.jpg": "2026-11-24T10:00"}
        got = scenes.order(self.items, set(last), last, seed="x")
        self.assertEqual([i["file"] for i in got], ["b.jpg", "d.jpg", "c.jpg", "a.jpg"])


class Always(unittest.TestCase):
    """assets() of any story, with Commons answering only for the vetted scene files, still carries a photo."""

    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.addCleanup(self.tmp.cleanup)
        info = {"width": 4000, "height": 2600, "url": "u", "thumburl": "t",
                "extmetadata": {"LicenseShortName": {"value": "CC BY 4.0"}, "Artist": {"value": "A. Photographer"}}}
        patches = [mock.patch.object(entities, "CACHE", Path(self.tmp.name)),
                   mock.patch.object(entities, "candidates", return_value=[]),
                   mock.patch.object(entities, "is_human", return_value=False),
                   mock.patch.object(entities, "logo", return_value=None),
                   mock.patch.object(entities, "ticker", return_value=None),
                   mock.patch.object(entities, "_commons_info", return_value=info),
                   mock.patch.object(entities, "_get", return_value=b"jpeg"),
                   mock.patch.object(templates, "USED", set()), mock.patch.object(templates, "LAST", {})]
        for p in patches:
            p.start()
            self.addCleanup(p.stop)

    def story(self, headline, topic, person, company):
        return {"headline": headline, "title": headline, "topic": topic, "person": person, "company": company}

    def test_no_story_is_left_without_a_photo(self):
        for headline, topic, person, company in WEB_HEADLINES:
            with self.subTest(headline=headline):
                a = templates.assets(self.story(headline, topic, person, company))
                self.assertTrue(a["photo"], "no photo")
                self.assertEqual(a["kind"], "scene")
                self.assertTrue(a["file"] and a["alt"] and a["credit"].startswith("Photo: A. Photographer, CC BY 4.0"))
                self.assertEqual(templates.layout(self.story(headline, topic, person, company) | {"_assets": a}), "photo")

    def test_a_scene_is_not_repeated_until_its_list_is_used_up(self):
        seen = []
        for i in range(4):
            a = templates.assets(self.story(f"Brent crude falls {i}", "Markets", "", ""))
            seen.append(a["file"])
        self.assertEqual(len(set(seen)), 4)
        self.assertTrue(all(len(self.tmp.name) and f for f in seen))

    def test_when_the_list_runs_out_the_longest_unused_file_comes_back(self):
        items = next(r["files"] for r in scenes.load()["rules"] if r["id"] == "energy")
        templates.USED.update(i["file"] for i in items)
        templates.LAST.update({i["file"]: f"2026-11-{10 + n:02d}T00:00:00" for n, i in enumerate(items)})
        a = templates.assets(self.story("Oil prices climb", "Markets", "", ""))
        self.assertEqual(a["file"], items[0]["file"])

    def test_without_network_there_is_no_photo_to_find(self):
        a = templates.assets(self.story("Oil prices climb", "Markets", "", ""), fetch=False)
        self.assertEqual(a["photo"], "")


class Gate(unittest.TestCase):
    def post(self, **kw):
        p = {"headlines": ["Global stocks rally"], "topic": "Markets", "body": "", "dek": "", "caption": "x #news",
             "photo_file": "Container cranes.jpg", "credit": "Photo: A, CC BY 4.0", "photo_kind": "scene"}
        return {**p, **kw}

    def test_a_post_without_a_photo_is_held(self):
        self.assertEqual(desk.audit(self.post()), [])
        self.assertIn("no photo", desk.audit(self.post(photo_file="", credit="", photo_kind="")))

    def test_the_front_page_shows_a_scene_photo(self):
        p = dict(id="x", headlines=["Global stocks rally"], dek="", topic="Markets", sources=["A", "B"], score=9, _thumb=True,
                 published="2026-11-26T12:00:00+00:00", photo_file="HH Hafen Kontainerbruecken.JPG", photo_kind="scene")
        self.assertTrue(views.photo_ok(p))
        self.assertFalse(views.photo_ok({**p, "photo_kind": ""}))
        other = {**p, "photo_file": "Bremerhaven - Containerterminal 02.jpg"}
        self.assertNotEqual(views.photo_subject(p), views.photo_subject(other))


